#!/usr/bin/env python3
"""
Waive the uplift supplement's K = 1 anchor evaluations in the register.

``scripts/verify_run_conditions.py`` requires every ``evaluation.json`` under
``results/`` to be either a registered condition or explicitly listed in its
run's ``_ignored_evals`` (so that a scored artefact cannot be silently
omitted from the register). The consensus-uplift supplement
(``planning/uplift-supplement-2026-08-28.md``) scored 102 single-pass K = 1
anchors -- 95 gap-fill and 7 verifier-pairing -- under
``results/uplift-supplement/`` (commit ``5bd514542``). They are inputs to the
supplement's pairing tables, each scored on the reference of the stratum it
pairs with; the supplement is not a registered analysis and the paper cites
none of them directly. Unwaived, they left 29 runs PARTIAL.

PI ruling, 2026-09-07 (``planning/reference-revision-2026-09-06.md``
changelog, "Register-verifier debt"): **waive them**, with a reason keyed to
the uplift card, generated by script rather than typed. This is that script.
It adds one ``{"eval_path", "reason"}`` entry per unclaimed anchor to the
owning run's ``_ignored_evals``; existing entries are left alone, so it is
idempotent, and the file's serialisation is preserved.

Usage::

    python scripts/waive_uplift_anchor_evals.py            # plan
    python scripts/waive_uplift_anchor_evals.py --write    # persist
    python scripts/verify_run_conditions.py                # confirm

Created: 2026-09-07 (Session 149-c)
Author: Shawn Ross, Claude Code
Licence: Apache 2.0
"""

from __future__ import annotations

import argparse
import json
import sys
from pathlib import Path

REPO = Path(__file__).resolve().parent.parent
RUN_CONDITIONS = REPO / "results/run-conditions.json"
ANCHOR_ROOT = REPO / "results/uplift-supplement"
ANCHOR_DIRS = ("k1-gapfill", "verifier-pairing")
#: The reason written on every NEW waiver. Entries already in the register keep
#: the text they were written with — the 2026-09-07 batch names the commit that
#: scored it (``5bd514542``), which is true of that batch and of nothing since,
#: so this text states the class rather than a commit. Amended 2026-09-10, when
#: the ``crop-manifest`` pairing rule resolved fourteen previously blocked
#: pv-diag-384 twins and scored them under the same directory.
REASON = (
    "uplift-supplement pairing/gap-fill anchor "
    "(planning/uplift-supplement-2026-08-28.md): an input to the supplement's "
    "pairing tables, scored on the reference, buffer, and frame of the stratum "
    "it pairs with; not a registered condition and not cited by the paper. "
    "Waived by PI ruling 2026-09-07 "
    "(planning/reference-revision-2026-09-06.md, register-verifier debt)."
)


def anchor_evals() -> dict[str, list[str]]:
    """Every anchor evaluation on disk, grouped by the run its directory names.

    Directory names are ``<run_id>__<condition label>``; the run id is the part
    before the double underscore.
    """
    by_run: dict[str, list[str]] = {}
    for d in ANCHOR_DIRS:
        for ev in sorted((ANCHOR_ROOT / d).glob("*/evaluation.json")):
            run_id = ev.parent.name.split("__", 1)[0]
            by_run.setdefault(run_id, []).append(str(ev.relative_to(REPO)))
    return by_run


def plan(dec: dict) -> list[tuple[str, str, str]]:
    """(run id, eval path, status) for every anchor; status add/present/no-run."""
    out = []
    for run_id, paths in anchor_evals().items():
        if run_id not in dec:
            out += [(run_id, p, "no-run") for p in paths]
            continue
        have = {e["eval_path"] if isinstance(e, dict) else e
                for e in dec[run_id].get("_ignored_evals", [])}
        out += [(run_id, p, "present" if p in have else "add") for p in paths]
    return out


def main() -> int:
    ap = argparse.ArgumentParser(description=__doc__,
                                 formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--write", action="store_true", help="Persist (default: plan only).")
    args = ap.parse_args()
    rc = json.loads(RUN_CONDITIONS.read_text())
    dec = rc["decomposition"]
    items = plan(dec)
    for run_id, path, status in items:
        if status != "present":
            print(f"  {status:8s} {run_id}: {path}")
    n_add = sum(s == "add" for _r, _p, s in items)
    n_norun = [(r, p) for r, p, s in items if s == "no-run"]
    print(f"{len(items)} anchor evaluations: {n_add} to waive, "
          f"{sum(s == 'present' for *_, s in items)} already waived, {len(n_norun)} in no run")
    if n_norun:
        print("STOP: anchors whose run is not in the register -- not waived, needs a look")
        return 1
    if not args.write:
        print("dry run -- pass --write to persist")
        return 0
    for run_id, path, status in items:
        if status == "add":
            dec[run_id].setdefault("_ignored_evals", []).append(
                {"eval_path": path, "reason": REASON})
    existing = RUN_CONDITIONS.read_text()
    trailing = "\n" if existing.endswith("\n") else ""
    RUN_CONDITIONS.write_text(json.dumps(rc, indent=1, ensure_ascii=False) + trailing)
    print(f"wrote {n_add} waiver(s) -> {RUN_CONDITIONS.relative_to(REPO)}; "
          f"now run scripts/verify_run_conditions.py")
    return 0


if __name__ == "__main__":
    sys.exit(main())
