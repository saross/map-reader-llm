"""
Stage 2: Verification Engine
============================

Description:
    This script acts as the "Reviewer" in the two-stage pipeline. It takes a list of
    candidate features (Bounding Boxes) generated by Stage 1, extracts high-resolution
    crops for each, and submits them to a specific "Verifier" prompt (v4.X).

    It can perform multiple iterations (voting) for robust consensus.

    Uses the google-genai SDK with ThinkingConfig support for Gemini 3 models.

Usage:
    python scripts/5_verify_crops.py \\
        --candidates outputs/results/v4.1/candidates.geojson \\
        --output outputs/results/v4.1/verified.geojson \\
        --config prompts/configs/verify_image-only.json \\
        --workers 10

Key Features:
    - Parallel Processing: Uses ThreadPoolExecutor for high throughput.
    - Component-Level Cropping: Extracts exact pixel data from original GeoTIFFs.
    - Visual Chain-of-Thought: Prompts the model to "Scan, Discriminate, Score".
    - Comprehensive Metadata: Full API response tracking via lib_llm_metadata.

Author: Shawn Ross, Adela Sobotkova
Licence: Apache 2.0
"""

